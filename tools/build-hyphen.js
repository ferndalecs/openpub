// Bundles the Hypher hyphenation engine with en-GB patterns into web/hyphen.js.
// Run from openpub/:
//   (cd tools/hyphen && npm install)      once; fetches hypher + hyphenation.en-gb
//   node tools/build-hyphen.js
const fs = require('fs');
const path = require('path');
const base = path.join(__dirname, 'hyphen', 'node_modules');
const hypher = fs.readFileSync(path.join(base, 'hypher', 'lib', 'hypher.js'), 'utf8');
const pat = fs.readFileSync(path.join(base, 'hyphenation.en-gb', 'lib', 'en-gb.js'), 'utf8');
const out = `// Generated by tools/build-hyphen.js - do not edit.
// Hypher (c) Bram Stein, BSD licence; en-GB patterns from the TeX hyphenation project.
// Exposes OpenPubHyphenate(text) -> text with soft hyphens at the allowed break points.
(function (root) {
  var Hypher = (function () { var module = { exports: {} };
${hypher}
  return module.exports; })();
  var lang = (function () { var module = { exports: {} };
${pat}
  return module.exports; })();
  lang.leftmin = 2; lang.rightmin = 2;
  var h = new Hypher(lang);
  var cache = new Map();
  root.OpenPubHyphenate = function (text) {
    return text.replace(/[A-Za-z\\u00C0-\\u024F]{5,}/g, function (w) {
      var r = cache.get(w);
      if (r === undefined) { r = h.hyphenate(w).join('\\u00AD'); cache.set(w, r); }
      return r;
    });
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(path.join(__dirname, '..', 'web', 'hyphen.js'), out);
console.log('web/hyphen.js written,', out.length, 'bytes');
